-- PostgreSQL version of schema.sql, used when DATABASE_URL is set (Cloud SQL).
-- Keep the two files in step: same tables, same columns, same keys. The
-- comments explaining each column live in schema.sql; only the dialect
-- differences are explained here.
--
-- Dialect differences, and why each matters:
--   * REAL in Postgres is 4-byte float. SQLite's REAL is an 8-byte double, and
--     verify_log.py's replay compares logged costs to 1e-6 -- a float4 cost
--     would fail it on every trial. Every REAL here is DOUBLE PRECISION.
--   * INTEGER is 4-byte. The participant seed is uniform on [0, 2^32), so half
--     of all seeds would overflow it: seed is BIGINT.
--   * AUTOINCREMENT -> GENERATED BY DEFAULT AS IDENTITY.
--   * No PRAGMAs (WAL and foreign keys are the defaults / always on).
--   * The whole file is idempotent (IF NOT EXISTS everywhere) and doubles as
--     the migration: db.py runs it once per process, under an advisory lock.

CREATE TABLE IF NOT EXISTS participant (
    participant_id   TEXT PRIMARY KEY,
    condition        TEXT NOT NULL CHECK (condition IN ('high', 'low')),
    prolific_pid     TEXT,
    seed             BIGINT NOT NULL,
    numeracy_score   INTEGER,
    started_utc      TEXT NOT NULL,
    finished_utc     TEXT,
    perceived_reliability INTEGER,
    consented        INTEGER NOT NULL DEFAULT 0,
    excluded         INTEGER NOT NULL DEFAULT 0,
    exclusion_reason TEXT,
    withdrawn_utc    TEXT,
    data_deleted     INTEGER NOT NULL DEFAULT 0,
    token_sha256     TEXT,
    device_ua        TEXT,
    screen_w         INTEGER,
    screen_h         INTEGER,
    viewport_w       INTEGER,
    pointer_coarse   INTEGER,
    app_version      TEXT NOT NULL,
    params_json      TEXT NOT NULL
);

-- Columns added after the first Postgres deployment go here as well as above,
-- so a database created by an earlier build catches up on the next boot.
ALTER TABLE participant ADD COLUMN IF NOT EXISTS token_sha256   TEXT;
ALTER TABLE participant ADD COLUMN IF NOT EXISTS device_ua      TEXT;
ALTER TABLE participant ADD COLUMN IF NOT EXISTS screen_w       INTEGER;
ALTER TABLE participant ADD COLUMN IF NOT EXISTS screen_h       INTEGER;
ALTER TABLE participant ADD COLUMN IF NOT EXISTS viewport_w     INTEGER;
ALTER TABLE participant ADD COLUMN IF NOT EXISTS pointer_coarse INTEGER;

CREATE TABLE IF NOT EXISTS trial (
    participant_id   TEXT NOT NULL REFERENCES participant(participant_id),
    trial_index      INTEGER NOT NULL,
    phase            TEXT NOT NULL CHECK (phase IN ('practice', 'main')),
    block            INTEGER NOT NULL,

    period           INTEGER NOT NULL,
    demand           INTEGER NOT NULL,
    inventory        INTEGER NOT NULL,
    on_order         INTEGER NOT NULL,
    lead_time        INTEGER NOT NULL,
    backorders       INTEGER NOT NULL,
    supplier_reliability DOUBLE PRECISION NOT NULL,
    transport_ok     INTEGER NOT NULL,
    disruption       TEXT NOT NULL,

    q_ai             INTEGER NOT NULL,
    ai_risk_pct      INTEGER NOT NULL,
    ai_level         TEXT NOT NULL,
    ai_correct       INTEGER NOT NULL,
    placement        TEXT NOT NULL CHECK (placement IN ('absorbed', 'propagating', 'neutral')),

    q_star           INTEGER NOT NULL,
    delta            INTEGER NOT NULL,

    q_own            INTEGER NOT NULL,
    q_final          INTEGER NOT NULL,
    response_class   TEXT NOT NULL CHECK (response_class IN ('accept','override','modify')),
    woa              DOUBLE PRECISION,
    error_own        INTEGER NOT NULL,
    error_final      INTEGER NOT NULL,
    own_correct      INTEGER NOT NULL,
    final_correct    INTEGER NOT NULL,

    rt_stage1_ms     INTEGER NOT NULL,
    rt_stage2_ms     INTEGER NOT NULL,

    demand_realised  INTEGER NOT NULL,
    cost             DOUBLE PRECISION NOT NULL,
    stockout         INTEGER NOT NULL,
    service_level    DOUBLE PRECISION NOT NULL,
    shipped          INTEGER NOT NULL,
    arrivals         INTEGER NOT NULL,
    inventory_close  INTEGER NOT NULL,
    backorders_close INTEGER NOT NULL,

    submitted_utc    TEXT NOT NULL,
    PRIMARY KEY (participant_id, phase, trial_index)
);

CREATE TABLE IF NOT EXISTS block_measure (
    participant_id   TEXT NOT NULL REFERENCES participant(participant_id),
    block            INTEGER NOT NULL,
    instrument       TEXT NOT NULL CHECK (instrument IN ('tia', 'tlx')),
    item             TEXT NOT NULL,
    response         DOUBLE PRECISION NOT NULL,
    recorded_utc     TEXT NOT NULL,
    PRIMARY KEY (participant_id, block, instrument, item)
);

CREATE TABLE IF NOT EXISTS event_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id   TEXT,
    kind             TEXT NOT NULL,
    detail           TEXT,
    recorded_utc     TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS screening (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numeracy_score   INTEGER NOT NULL,
    passed           INTEGER NOT NULL,
    recorded_utc     TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS pending_stage1 (
    participant_id   TEXT PRIMARY KEY REFERENCES participant(participant_id),
    phase            TEXT NOT NULL CHECK (phase IN ('practice', 'main')),
    trial_index      INTEGER NOT NULL,
    q_own            INTEGER NOT NULL,
    rt_stage1_ms     INTEGER NOT NULL,
    advice_json      TEXT NOT NULL,
    recorded_utc     TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_trial_participant ON trial(participant_id, phase, trial_index);
CREATE INDEX IF NOT EXISTS idx_event_participant ON event_log(participant_id, id);
